encoder get_speed(void)
{
  encoder encoder;

  int32_t counterValue = (int32_t)__HAL_TIM_GET_COUNTER(&htim2);

  int32_t delta_count = counterValue - pastCounterValue;
  if (delta_count > 32767) {
      delta_count -= 65536;
  } else if (delta_count < -32768) {
      delta_count += 65536;
  }

  float tours = (float)delta_count / RESOLUTION_ENCODEUR;

  encoder.speed = tours * 60.0f / Te;

  encoder.angle = fmodf((float)counterValue * 360.0f / RESOLUTION_ENCODEUR,360.0f);

  pastCounterValue = counterValue;

  return encoder;
}

